import { v2 as cloudinary } from "cloudinary";
import { env } from "./env";
import { AppError } from "./http/errors";
import type { ImageUpload } from "./validation/upload";

export type ImageFolder = "resources/vehicles" | "resources/drivers" | "public/images/experiences" | "public/images/destinations";
export type StoredImage = { secureUrl: string; publicId: string };

// Server-only. Credentials come from the environment and are applied on first use.
let configured = false;
function client() {
  if (!configured) {
    const { cloudName, apiKey, apiSecret } = env.cloudinary;
    if (!cloudName || !apiKey || !apiSecret) throw new Error("CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY and CLOUDINARY_API_SECRET must be set");
    cloudinary.config({ cloud_name: cloudName, api_key: apiKey, api_secret: apiSecret, secure: true });
    configured = true;
  }
  return cloudinary;
}

// Uploads an already-validated image buffer. The public_id is generated by Cloudinary, never taken from the client.
export async function uploadImage(image: ImageUpload, folder: ImageFolder): Promise<StoredImage> {
  const api = client();
  try {
    const result = await new Promise<{ secure_url: string; public_id: string }>((resolve, reject) => {
      const stream = api.uploader.upload_stream(
        { folder, resource_type: "image", allowed_formats: ["jpg", "png", "webp"] },
        (error, uploaded) => (error || !uploaded ? reject(error ?? new Error("Empty Cloudinary response")) : resolve(uploaded)),
      );
      stream.end(image.data);
    });
    return { secureUrl: result.secure_url, publicId: result.public_id };
  } catch (error) {
    console.error("[cloudinary] upload failed", error);
    throw new AppError("INTERNAL", "The picture could not be uploaded. Please try again.");
  }
}

// Best effort: a failed cleanup is logged, never thrown, so it cannot undo a database change that already committed
export async function deleteImage(publicId: string | null | undefined): Promise<void> {
  if (!publicId) return;
  try {
    await client().uploader.destroy(publicId, { resource_type: "image", invalidate: true });
  } catch (error) {
    console.error("[cloudinary] could not delete", publicId, error);
  }
}
